    def test_create_and_execute_persisted_message_parameter_version(self):
        from configuration.models.firewall_config import FirewallConfiguration
        from configuration.models.ruleset_config import RulesetConfig
        from configuration.models.rule_config import RuleConfig
        from configuration.models.condition_group_config import ConditionGroupConfig
        from configuration.models.condition_config import ConditionConfig
        from configuration.models.action_config import ActionConfig

        from conditions.enums import SourceType, Operator, MatchMode
        from conditions.evaluator import ConditionEvaluator
        from conditions.group_evaluator import ConditionGroupEvaluator
        from rules.evaluator import RuleEvaluator
        from rules.operation_executor import OperationExecutor
        from runtime.runtime import FirewallRuntime

        from storage.json_storage import JsonStorage
        from versions.version_repository import VersionRepository
        from versions.version_service import VersionService

        storage_path = (
            Path(__file__).resolve().parents[1]
            / "storage"
            / "versions"
        )

        service = VersionService(
            repository=VersionRepository(),
            storage=JsonStorage(str(storage_path)),
        )

        # Avoid creating duplicate versions on repeated test runs.
        existing = next(
            (
                version
                for version in service.list_versions()
                if version.name == "Message Parameter Integration"
            ),
            None,
        )

        if existing is not None:
            version = existing
        else:
            configuration = FirewallConfiguration()
            ruleset = RulesetConfig(name="Message Parameter Checks")

            parameter_names = [
                "Message-Id",
                "Message-Sender",
                "Message-Recipient",
                "Message-Text",
                "Message-Headers",
            ]

            for parameter_name in parameter_names:
                rule = RuleConfig(name=f"Check {parameter_name}")

                rule.set_condition_group(
                    ConditionGroupConfig(
                        operator="AND",
                        conditions=[
                            ConditionConfig(
                                left_type=SourceType.PARAMETER.value,
                                left_name=parameter_name,
                                operator=Operator.EXISTS.value,
                                match_mode=MatchMode.ANY.value,
                            )
                        ],
                    )
                )

                rule.set_action(ActionConfig(type="CONTINUE"))
                ruleset.add_rule(rule)

            configuration.add_ruleset(ruleset)

            version = service.create_version(
                configuration=configuration,
                name="Message Parameter Integration",
                description=(
                    "Persisted rules verifying all five message "
                    "reception system parameters"
                ),
            )

        # Reload the persisted version using a fresh service.
        reloaded_service = VersionService(
            repository=VersionRepository(),
            storage=JsonStorage(str(storage_path)),
        )

        saved_version = reloaded_service.get_version(str(version.id))

        # Repositories may accept UUID objects rather than strings.
        if saved_version is None:
            saved_version = reloaded_service.get_version(version.id)

        assert saved_version is not None
        assert saved_version.name == "Message Parameter Integration"

        saved_configuration = saved_version.configuration

        evaluator = RuleEvaluator(
            condition_group_evaluator=ConditionGroupEvaluator(
                ConditionEvaluator()
            ),
            operation_executor=OperationExecutor(),
        )

        runtime = FirewallRuntime(
            configuration=saved_configuration,
            rule_evaluator=evaluator,
        )

        envelope = create_message_envelope(
            sender="sender@example.com",
            recipient="recipient@example.com",
            text="Persisted configuration test",
            headers={"Subject": "Version 5"},
        )

        context = ExecutionContext()

        from engine.message_parameters import load_message_parameters
        load_message_parameters(envelope, context)

        result = runtime.execute(
            "Message Parameter Checks",
            context,
        )

        assert result is not None
        assert result.__class__.__name__ == "ContinueAction"
        assert context.get_ruleset_path() == []
        assert len(saved_configuration.rulesets[0].rules) == 5

        
