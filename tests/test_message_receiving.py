class TestMessageReceiving:

    def test_create_message_envelope(self):
        envelope = create_message_envelope(
            sender="sender@example.com",
            recipient="recipient@example.com",
            text="Hello firewall",
            headers={"Subject": "Test message"},
        )

        assert envelope["message_id"]
        assert envelope["sender"] == "sender@example.com"
        assert envelope["recipient"] == "recipient@example.com"
        assert envelope["text"] == "Hello firewall"
        assert envelope["headers"] == {
            "Subject": "Test message"
        }

    def test_message_envelopes_have_unique_ids(self):
        first = create_message_envelope(
            sender="a@example.com",
            recipient="b@example.com",
            text="First message",
        )

        second = create_message_envelope(
            sender="a@example.com",
            recipient="b@example.com",
            text="Second message",
        )

        assert first["message_id"] != second["message_id"]

    def test_missing_headers_default_to_empty_dictionary(self):
        envelope = create_message_envelope(
            sender="sender@example.com",
            recipient="recipient@example.com",
            text="Hello",
        )

        assert envelope["headers"] == {}

    def test_headers_are_copied(self):
        headers = {"Subject": "Original"}

        envelope = create_message_envelope(
            sender="sender@example.com",
            recipient="recipient@example.com",
            text="Hello",
            headers=headers,
        )

        envelope["headers"]["Subject"] = "Changed"

        assert headers["Subject"] == "Original"

